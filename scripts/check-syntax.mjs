// scripts/check-syntax.mjs
// Contract for the two gates `flet-box verify` gained: the parse gate and the
// test-suite gate.
//
// The bug these guard: the four gates read code as text — `check-api` resolves
// names, `check-ui` scans literals, `check-structure` follows imports — and none
// of them compiles a file. A module with an unclosed parenthesis passed all
// four, exit 0, "the code is legal", and the app came up blank in the browser.
// The second half is the same kind of silence: `verify` used to answer with a
// skipped "tests" step in this repository, so the one command an agent runs
// after an edit never ran the suites that name a broken rule.
//
// Both directions are asserted. A broken fixture must be reported with the
// line, the column, the offending source line with a caret under it and a
// suggestion — otherwise an agent reads `Unexpected token` and guesses. A clean
// project must report nothing, a file inside node_modules/www/dist must not be
// parsed, and neither must a VCS database or a vendor cache — or the gate would
// pass by flagging everything. Hidden project folders (`.qoder/skills`) are the
// opposite case: their scripts run, so they are parsed.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { scanSyntax, syntaxFiles } from "../bin/commands/checkSyntax.js";
import { formatReport, runGates, verify } from "../bin/commands/verify.js";

// `flet-box verify` runs `npm test` with this set so a test script cannot call
// verify back. This file is the one consumer that must see the gate from the
// outside — it asserts what a top-level run does — so it starts as top-level.
delete process.env.FLETBOX_VERIFY_NESTED;

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "fletbox-syntax-"));

let failures = 0;
const check = (label, fn) => {
  try {
    fn();
    console.log(`✅ ${label}`);
  } catch (error) {
    failures += 1;
    console.log(`❌ ${label}\n     ${error.message}`);
  }
};

const assert = (condition, message) => {
  if (!condition) throw new Error(message);
};

const write = (rel, body) => {
  const target = path.join(scratch, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body, "utf8");
  return target;
};

const cleanDir = path.join(scratch, "clean");
const brokenDir = path.join(scratch, "broken");

write("clean/package.json", JSON.stringify({ name: "clean", type: "module" }));
write("clean/src/app.js", 'import { Text } from "flet-box";\nexport default () => [Text({ text: "ok" })];\n');
write(
  "clean/.qoder/skills/probe/scripts/tool.mjs",
  'export const ok = () => "hidden folders are the project\'s own code";\n',
);
// Build output and dependencies are somebody else's code: a parse error there
// is not this project's finding.
write("clean/node_modules/dep/index.js", "export const = ;\n");
write("clean/www/bundle.js", "const = ;\n");
write("clean/dist/app.js", "const = ;\n");
// A VCS database and a vendor cache are not parsed either — `.git` is full of
// generated bytes and `.yarn` ships its own compiler.
write("clean/.git/hooks/pre-commit.js", "const = ;\n");
write("clean/.yarn/releases/yarn.cjs", "const = ;\n");

write("broken/package.json", JSON.stringify({ name: "broken", type: "module" }));
const paren = write(
  "broken/src/paren.js",
  'import { Text } from "flet-box";\n\nexport const screen = () => [Text({ text: "a" };\n',
);
write("broken/src/tick.js", 'import { Text } from "flet-box";\n\nexport const label = `hello;\n');
write("broken/src/smart.js", "export const title = \u201cHola\u201d;\n");

// A hidden folder is the project's own code — the maintenance playbooks ship in
// `.qoder/skills` — while `.git` and a vendor cache are somebody else's bytes.
const hiddenDir = path.join(scratch, "hidden");
write("hidden/package.json", JSON.stringify({ name: "hidden", type: "module" }));
const hiddenBroken = write("hidden/.qoder/skills/probe/scripts/tool.mjs", "export const tool = (;\n");
write("hidden/.git/hooks/pre-commit.js", "const = ;\n");
write("hidden/.yarn/releases/yarn.cjs", "const = ;\n");

const suite = (name, scripts) => {
  const dir = path.join(scratch, name);
  write(`${name}/package.json`, JSON.stringify({ name, type: "module", scripts }));
  return dir;
};
const failing = suite("suite-fail", {
  test: 'node -e "console.error(\'❌ boom: the rule\'); process.exit(3)"',
});
const passing = suite("suite-pass", { test: 'node -e "console.log(\'ok\')"' });
const none = suite("suite-none", {});

try {
  // ---------------------------------------------------------------- parsing

  const clean = await scanSyntax(cleanDir);
  check("a clean project reports nothing — build output, .git and a vendor cache are not parsed", () => {
    assert(clean.length === 0, `${clean.length} finding(s) in a clean project`);
    const scanned = syntaxFiles(cleanDir).map((file) => path.relative(cleanDir, file));
    assert(
      scanned.includes(path.join(".qoder", "skills", "probe", "scripts", "tool.mjs")),
      `the clean hidden module was skipped: ${scanned.join(", ")}`,
    );
  });

  check("a module that cannot parse is reported, one finding per file", () => {
    const files = syntaxFiles(brokenDir).map((file) => path.relative(brokenDir, file));
    assert(files.includes("src/paren.js"), `the scan missed src/paren.js: ${files.join(", ")}`);
    assert(files.length === 3, `expected 3 modules, got ${files.length}: ${files.join(", ")}`);
  });

  const findings = await scanSyntax(brokenDir);
  const parenFinding = findings.find((item) => item.file === paren);

  check("a hidden project folder is parsed; a VCS database and a vendor cache are not", () => {
    const files = syntaxFiles(hiddenDir).map((file) => path.relative(hiddenDir, file));
    assert(
      files.includes(path.join(".qoder", "skills", "probe", "scripts", "tool.mjs")),
      `the scan missed the module under .qoder: ${files.join(", ")}`,
    );
    assert(
      !files.some((file) => file.startsWith(".git") || file.startsWith(".yarn")),
      `a database or a vendor cache was parsed: ${files.join(", ")}`,
    );
  });

  const hiddenFindings = await scanSyntax(hiddenDir);
  check("a parse error inside a hidden folder is reported, and only that one", () => {
    assert(hiddenFindings.length === 1, `expected 1 finding, got ${hiddenFindings.length}`);
    assert(hiddenFindings[0].file === hiddenBroken, `reported ${hiddenFindings[0].file}`);
  });

  check("the finding carries the line, the column and the marked source line", () => {
    assert(parenFinding, "the unclosed call was not reported");
    assert(parenFinding.line === 3, `line ${parenFinding.line}, expected 3`);
    assert(parenFinding.column > 0, "no column: the caret was not read from the parser output");
    assert(
      parenFinding.detail.includes('Text({ text: "a" };') && /\n\s*\^/.test(parenFinding.detail),
      `the detail has no caret under the line: ${JSON.stringify(parenFinding.detail)}`,
    );
  });

  check("each parse error suggests what the line above usually got wrong", () => {
    assert(
      /parenthes/i.test(parenFinding.suggestion),
      `unclosed call suggests: ${parenFinding.suggestion}`,
    );
    const tick = findings.find((item) => item.file.endsWith("tick.js"));
    assert(/backtick/i.test(tick.suggestion), `unclosed template suggests: ${tick.suggestion}`);
    const smart = findings.find((item) => item.file.endsWith("smart.js"));
    assert(/character/i.test(smart.suggestion), `smart quote suggests: ${smart.suggestion}`);
  });

  const syntaxReport = await runGates(brokenDir, ["syntax"]);
  check("the report prints file:line:column, not just the file", () => {
    const text = formatReport(syntaxReport).join("\n").replace(/\u001b\[[0-9;]*m/g, "");
    const at = `src/paren.js:${parenFinding.line}:${parenFinding.column}`;
    assert(text.includes(at), `the report does not name ${at}:\n${text}`);
  });

  // The other half of "name the cause": a warning is not a failure, but it is
  // still a line an agent has to read. It used to be counted and never printed.
  const warned = {
    root: scratch,
    package: "1.0.0",
    steps: [
      {
        name: "ui",
        title: "Design gate",
        exitCode: 0,
        findings: [
          {
            code: "ICON_ONLY_CONTROL",
            file: path.join(scratch, "src", "app.js"),
            line: 7,
            column: 12,
            message: "Icon is pressable and carries no name.",
            detail: "",
            suggestion: 'name it with "aria-label": "Share"',
            severity: "warn",
          },
        ],
      },
    ],
  };
  check("a warning is printed with its file, its line, its code and its suggestion", () => {
    const text = formatReport(warned).join("\n").replace(/\u001b\[[0-9;]*m/g, "");
    assert(/what to review/.test(text), `no review section:\n${text}`);
    assert(text.includes("src/app.js:7:12"), `no file:line:column:\n${text}`);
    assert(text.includes("ICON_ONLY_CONTROL"), `no code:\n${text}`);
    assert(/aria-label/.test(text), `no suggestion:\n${text}`);
    assert(/1 warning\(s\)/.test(text), `the summary hides the warning:\n${text}`);
  });

  // ------------------------------------------------------------ the suites

  const failed = await runGates(failing, ["tests"]);
  check("a failing suite fails the gate and keeps the suite's own last words", () => {
    const step = failed.steps[0];
    assert(step.exitCode === 1, "a failing npm test did not fail the gate");
    const finding = step.findings[0];
    assert(finding && finding.code === "TEST_SUITE_FAILED", "no TEST_SUITE_FAILED finding");
    assert(/exited 3/.test(finding.message), `message: ${finding.message}`);
    assert(finding.detail.includes("boom: the rule"), `detail: ${JSON.stringify(finding.detail)}`);
    // `npm run … --silent`: npm's own error block would bury the check's line.
    assert(!/npm error/.test(finding.detail), "the detail is npm's noise, not the check's words");
  });

  const green = await runGates(passing, ["tests"]);
  check("a green suite passes the gate", () => {
    assert(green.steps[0].exitCode === 0, "a passing suite failed the gate");
    assert(green.steps[0].findings.length === 0, "a passing suite produced findings");
    assert(!green.steps[0].skipped, "a declared suite was reported as skipped");
  });

  const absent = await runGates(none, ["tests"]);
  check("a project that declares no suite is skipped, not failed", () => {
    assert(absent.steps[0].exitCode === 0, "a project with no suite failed the gate");
    assert(/no test script/.test(absent.steps[0].skipped || ""), `skipped: ${absent.steps[0].skipped}`);
  });

  process.env.FLETBOX_VERIFY_NESTED = "1";
  const nested = await runGates(failing, ["tests"]);
  delete process.env.FLETBOX_VERIFY_NESTED;
  check("a verify inside a verify does not run the suites again", () => {
    assert(nested.steps[0].exitCode === 0, "the nested run executed the suite");
    assert(/already inside/.test(nested.steps[0].skipped || ""), `skipped: ${nested.steps[0].skipped}`);
  });

  const lines = [];
  await verify(["--root", cleanDir, "--json"], { print: (line) => lines.push(line) });
  const json = JSON.parse(lines.join("\n"));
  check("verify runs the parse gate and the suite gate by default", () => {
    const names = json.steps.map((step) => step.name);
    assert(names.includes("syntax"), `the default run does not parse: ${names.join(", ")}`);
    assert(names.includes("tests"), `the default run does not run the suites: ${names.join(", ")}`);
    const tests = json.steps.find((step) => step.name === "tests");
    assert(/no test script/.test(tests.skipped || ""), `skipped: ${tests.skipped}`);
  });

  // CI runs the suites in their own jobs, so it asks verify to leave them out.
  // That choice is the caller's and it is stated: the report must not borrow the
  // "already inside a verify run" note, which is about nesting and is false here
  // — and a failing suite must not be able to fail a run that skipped it.
  const staticOnly = await verify(["--root", failing, "--no-tests"], { print: () => {} });
  check("--no-tests leaves the suites out, and a failing suite cannot fail that run", () => {
    const names = staticOnly.report.steps.map((step) => step.name);
    assert(!names.includes("tests"), `--no-tests still ran the suites: ${names.join(", ")}`);
    assert(names.length === 5, `expected the five static gates, got: ${names.join(", ")}`);
    assert(staticOnly.exitCode === 0, "a suite that was not run decided the exit code");
  });
} finally {
  fs.rmSync(scratch, { recursive: true, force: true });
}

if (failures) {
  console.log(`\ncheck-syntax: ${failures} failed`);
  process.exit(1);
}
console.log("\ncheck-syntax: the parser and the suites are gates, and both bite");
